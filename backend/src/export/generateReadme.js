import { PACKAGE_CATALOG } from "./packageCatalog.js";

export function generateReadme(nodes, dashboardEnabled) {
  const byType = new Map();
  for (const n of nodes) {
    if (!byType.has(n.type)) byType.set(n.type, []);
    byType.get(n.type).push(n);
  }
  const cacheIncluded = byType.has("cache");
  const lbIncluded = byType.has("loadbalancer");
  const healthIncluded = byType.has("health");

  const sections = [...byType.entries()].map(([type, instances]) => {
    const pkg = PACKAGE_CATALOG[type];
    const envLines = pkg.envVars.length ? pkg.envVars.map((v) => `- \`${v}\``).join("\n") : "- none";
    const multiNote =
      instances.length > 1
        ? `\n> ${instances.length} instances placed (${instances
            .map((i) => i.nickname || type)
            .join(", ")}) — see the NOTE in \`infrakit.config.js\` about today's single-block limitation.\n`
        : "";
    return `### ${pkg.npmName}

${pkg.description}
${multiNote}
\`\`\`
npm install ${pkg.npmName}
\`\`\`

**Env vars:**
${envLines}
`;
  });

  return `# InfraKit Setup

Generated by InfraKit Visual Editor. Drop \`infrakit.config.js\`, \`setup-infrakit.js\`${dashboardEnabled ? ", `infrakit-dashboard-login.js`, `infrakit-dashboard-auth-check.js`" : ""} into your Node.js repo and require them from your app entrypoint.

${sections.join("\n---\n\n")}

---
${healthIncluded
  ? `## One manual step: health checks

\`@infrakit/health\`'s \`checks\` array takes real JS check functions
(\`createHttpCheck(name, url, opts)\`), which can't be generated from the
property panel. Add them to \`infrakit.config.js\` by hand.

`
  : ""}${dashboardEnabled
  ? `## Dashboard access — login once, checked continuously

Visit \`/infrakit-access\` (mounted by \`infrakit-dashboard-login.js\`) and
enter the **Project Key** and **Password** shown once on your export
screen (\`.env.infrakit-secrets\`: \`DASHBOARD_ACCESS_KEY\` /
\`DASHBOARD_ACCESS_PASSWORD\`). That's the only login a person operating
this dashboard needs to know.

Behind the scenes: this endpoint verifies those two values with the
platform server-to-server, shows you which project you're looking at, then
completes \`@infrakit/dashboard\`'s own real login for you — using
\`DASHBOARD_USERNAME\` / \`DASHBOARD_PASSWORD\` from \`.env\`, which it reads
itself. You never have to type those two separately; they exist because
\`@infrakit/dashboard\` has its own built-in login with no way to disable it
or accept an externally-issued session, so this file logs into it on your
behalf after the platform vouches for you.

**\`infrakit-dashboard-auth-check.js\` doesn't stop at login.** It's mounted
in front of the dashboard's entire route path (not just \`/login\`), and
re-verifies with the platform every 60 seconds using the same
\`DASHBOARD_ACCESS_KEY\`/\`PASSWORD\` from \`.env\` — server-to-server, never
exposed to the browser. This means the platform can revoke this project's
dashboard access at any time, and it takes effect within about a minute,
even for someone who already has a valid dashboard session cookie. If the
platform is briefly unreachable, this fails open (reuses the last known-good
result) rather than locking you out of your own server — flip
\`FAIL_CLOSED_ON_PLATFORM_ERROR\` in that file if you'd rather prioritize
strictness over availability.

**Worth knowing:** the login relay only works because
\`infrakit-dashboard-login.js\` dispatches a request through your app's own
instance to reach dashboard's real login route — it's coupled to today's
\`@infrakit/dashboard\` internals (its login path, its \`username\`/\`password\`
field names, and the fact that it responds with a \`Set-Cookie\` header on
success). If a future dashboard version changes that shape, both dashboard
files here will need a matching update.

`
  : ""}${cacheIncluded
  ? `## Cache encryption

If you want per-value AES-256-GCM encryption in \`@infrakit/cache\`, set
your own \`CACHE_ENCRYPTION_KEY\` in \`.env\`. This tool never generates or
stores this key for you.

`
  : ""}${lbIncluded
  ? `## Load balancer alert emails

\`smart-stick-loadbalancer\`'s optional down/up email alerts need
\`LB_ALERT_EMAIL\` and \`LB_ALERT_PASS\` (a Gmail App Password) in \`.env\`.
Omit both to disable alerts entirely.

`
  : ""}## Docker

Docker: not yet available, run directly with Node for now.
`;
}
