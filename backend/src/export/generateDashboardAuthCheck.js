/**
 * Generates infrakit-dashboard-auth-check.js: middleware that gates the
 * ENTIRE @infrakit/dashboard base path (not just the login route) behind a
 * live, repeated check with the platform — so the platform can revoke a
 * project's dashboard access at any time, not just at the moment someone
 * logs in through infrakit-dashboard-login.js.
 *
 * SECURITY SHAPE, DELIBERATELY CHOSEN:
 * This check runs server-to-server, using DASHBOARD_ACCESS_KEY/PASSWORD
 * already sitting in this app's own .env — never in browser JS, never in a
 * cookie the browser controls, no CORS surface exposed on the platform for
 * arbitrary customer origins. The browser never talks to the platform
 * directly; it only ever talks to this app, which is the one making the
 * server-to-server call. This reuses the EXISTING /auth/verify-credentials
 * endpoint rather than adding new platform surface.
 *
 * Mounted in front of the dashboard's entire base path (not just /login) so
 * it can't be bypassed by someone who already knows dashboard's own raw
 * username/password and goes straight to its login route.
 *
 * TRADEOFFS, STATED EXPLICITLY RATHER THAN LEFT IMPLICIT:
 * - Result is cached for CHECK_CACHE_MS so every dashboard click doesn't
 *   trigger a platform round-trip. Revocation takes effect within that
 *   window, not instantly.
 * - Fails OPEN on network errors to the platform (last known-good result is
 *   reused) — a platform outage shouldn't lock someone out of their own
 *   server. Flip FAIL_CLOSED_ON_PLATFORM_ERROR below if you'd rather
 *   prioritize strictness over availability.
 */
export function generateDashboardAuthCheckMiddleware({ platformOrigin, dashboardBasePath = "/infrakit" }) {
  return `// Generated by InfraKit Visual Editor.
// Mount this BEFORE dashboard.init(app, ...), at the SAME base path:
//   app.use("${dashboardBasePath}", require("./infrakit-dashboard-auth-check.js"));
//   dashboard.init(app, config.dashboard || {});
//
// Requires in .env: DASHBOARD_ACCESS_KEY, DASHBOARD_ACCESS_PASSWORD — the
// same two values from your export screen, already in .env if you set up
// infrakit-dashboard-login.js. No new secret to manage.
const PLATFORM_ORIGIN = ${JSON.stringify(platformOrigin)};
const CHECK_CACHE_MS = 60 * 1000; // how often to actually re-check with the platform
const FAIL_CLOSED_ON_PLATFORM_ERROR = false; // true = block access if the platform can't be reached at all (no cached result yet)

let cached = null; // { valid: boolean, checkedAt: number }

async function checkWithPlatform() {
  const accessKey = process.env.DASHBOARD_ACCESS_KEY;
  const password = process.env.DASHBOARD_ACCESS_PASSWORD;
  if (!accessKey || !password) {
    console.warn("[infrakit-dashboard-auth-check] DASHBOARD_ACCESS_KEY/PASSWORD not set in .env — failing closed.");
    return false;
  }
  try {
    const resp = await fetch(\`\${PLATFORM_ORIGIN}/auth/verify-credentials\`, {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify({ accessKey, password }),
    });
    const result = await resp.json();
    return !!result.valid;
  } catch (err) {
    console.warn("[infrakit-dashboard-auth-check] Could not reach the platform:", err.message);
    if (cached) return cached.valid; // reuse last known-good result rather than flip-flopping on a blip
    return !FAIL_CLOSED_ON_PLATFORM_ERROR;
  }
}

function renderRevoked() {
  return \`<!doctype html><html><head><title>Access Unavailable</title>
<style>
  body { font-family: -apple-system, sans-serif; background: #f7f7f8; display: flex;
         align-items: center; justify-content: center; height: 100vh; margin: 0; }
  .card { background: white; padding: 32px; border-radius: 12px; width: 320px; text-align: center;
          box-shadow: 0 4px 20px rgba(0,0,0,0.08); }
  h1 { font-size: 16px; margin: 0 0 8px; }
  p { color: #666; font-size: 13px; margin: 0; }
</style></head><body>
<div class="card">
  <h1>Dashboard access unavailable</h1>
  <p>This project's dashboard access is not currently authorized. Contact whoever manages this project's platform account.</p>
</div>
</body></html>\`;
}

module.exports = async function infrakitDashboardAuthCheck(req, res, next) {
  const fresh = cached && Date.now() - cached.checkedAt < CHECK_CACHE_MS;
  if (!fresh) {
    const valid = await checkWithPlatform();
    cached = { valid, checkedAt: Date.now() };
  }

  if (cached.valid) return next();
  return res.status(403).send(renderRevoked());
};
`;
}
