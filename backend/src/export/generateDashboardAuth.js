/**
 * Signed-token verification middleware (spec option (a): local JWT
 * verification using the per-project secret — no network call, works
 * offline). Nothing about the redirect URL itself is ever trusted; only the
 * JWT signature + expiry decide access.
 */
export function generateDashboardAuthMiddleware({ projectId, platformOrigin }) {
  return `// Generated by InfraKit Visual Editor.
// Mount this in front of your @infrakit/dashboard route:
//   app.use("/infrakit/dashboard", require("./infrakit-dashboard-auth.js"));
//
// Requires INFRAKIT_DASHBOARD_SECRET in your .env — the plaintext secret was
// shown once on the export screen. This file never contains the secret itself.
const jwt = require("jsonwebtoken");

const PROJECT_ID = "${projectId}";
const PLATFORM_ORIGIN = "${platformOrigin}";
const SECRET = process.env.INFRAKIT_DASHBOARD_SECRET;

if (!SECRET) {
  throw new Error("INFRAKIT_DASHBOARD_SECRET is not set — dashboard auth cannot verify tokens.");
}

module.exports = function infrakitDashboardAuth(req, res, next) {
  const token = req.query.token || req.query.ike_token;

  if (!token) {
    const returnTo = encodeURIComponent(req.protocol + "://" + req.get("host") + req.originalUrl);
    const verifyUrl = \`\${PLATFORM_ORIGIN}/auth/verify?project_id=\${PROJECT_ID}&return_to=\${returnTo}\`;
    return res.redirect(verifyUrl);
  }

  try {
    const payload = jwt.verify(token, SECRET);
    if (payload.project_id !== PROJECT_ID) {
      return res.status(403).send("Token was not issued for this project.");
    }
    // Signature valid, not expired, right project — nothing about the
    // redirect URL itself was trusted to get here.
    req.infrakitAuth = payload;
    return next();
  } catch (err) {
    return res.status(401).send("Invalid or expired dashboard access token.");
  }
};
`;
}
