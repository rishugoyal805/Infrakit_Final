import { PACKAGE_CATALOG } from "./packageCatalog.js";

function serializeValue(fieldType, raw) {
  if (fieldType === "json") {
    try {
      return JSON.stringify(JSON.parse(raw), null, 2).replace(/\n/g, "\n    ");
    } catch {
      return raw;
    }
  }
  if (fieldType === "string") return JSON.stringify(raw);
  return raw; // number / boolean
}

function fieldsToObjectLiteral(pkgType, values) {
  const catalog = PACKAGE_CATALOG[pkgType];
  const lines = catalog.fields.map((f) => {
    const raw = values && Object.prototype.hasOwnProperty.call(values, f.key) ? values[f.key] : f.default;
    return `      ${f.key}: ${serializeValue(f.type, raw)},`;
  });

  if (pkgType === "cache") {
    lines.push(`      encryptionKey: process.env.CACHE_ENCRYPTION_KEY,`);
  }
  if (pkgType === "loadbalancer") {
    lines.push(
      `      // Omit this whole "email" block entirely if you don't want alert emails.`,
      `      email: process.env.LB_ALERT_EMAIL ? {`,
      `        service: "gmail",`,
      `        auth: { user: process.env.LB_ALERT_EMAIL, pass: process.env.LB_ALERT_PASS },`,
      `      } : undefined,`
    );
  }
  if (pkgType === "dashboard") {
    lines.push(`      username: process.env.DASHBOARD_USERNAME,`, `      password: process.env.DASHBOARD_PASSWORD,`);
  }
  if (pkgType === "health") {
    lines.push(
      `      // TODO: add checks by hand — createHttpCheck(...) returns a JS`,
      `      // function, which can't be expressed in this generated file.`,
      `      checks: [],`
    );
  }

  return lines.length ? `{\n${lines.join("\n")}\n    }` : "{}";
}

/**
 * nodes: [{ id, type, nickname, values }] — one entry per placed InfraKit
 * node. Multiple nodes can share a `type` (multiple instances of the same
 * package, each with its own nickname and values).
 *
 * IMPORTANT REAL-WORLD CAVEAT: as of this codebase's current code, every
 * @infrakit/* package reads exactly ONE flat top-level config block at
 * runtime (e.g. core.config().rateLimiter) — none of them know how to look
 * up a nicknamed sub-block. So:
 *   - Exactly one instance of a type -> a flat block, matching what the
 *     real package actually reads today. No caveat needed.
 *   - Multiple instances of a type -> nested by nickname, with a loud
 *     comment explaining this is forward-looking scaffolding, not
 *     something the current package version can act on by itself.
 */
export function generateInfrakitConfig(nodes, dashboardEnabled) {
  const byType = new Map();
  for (const n of nodes) {
    if (!byType.has(n.type)) byType.set(n.type, []);
    byType.get(n.type).push(n);
  }

  const blockLines = [];
  for (const [type, instances] of byType) {
    const catalog = PACKAGE_CATALOG[type];
    if (!catalog || !catalog.configKey) continue; // shouldn't happen — core/unknown types are filtered before this is called

    if (instances.length === 1) {
      blockLines.push(`  ${catalog.configKey}: ${fieldsToObjectLiteral(type, instances[0].values)},`);
    } else {
      blockLines.push(
        `  // NOTE: ${instances.length} "${type}" nodes were placed on the canvas, nested here`,
        `  // by nickname. @infrakit/${type} currently reads ONE flat "${catalog.configKey}"`,
        `  // block at runtime — it doesn't yet know how to look up a nicknamed`,
        `  // sub-block. This shape is forward-looking: today, only one of these`,
        `  // will actually take effect unless the package is extended to accept`,
        `  // a per-instance key.`,
        `  ${catalog.configKey}: {`,
        ...instances.map(
          (inst, i) => `    ${JSON.stringify(inst.nickname?.trim() || `${type}_${i + 1}`)}: ${fieldsToObjectLiteral(type, inst.values)},`
        ),
        `  },`
      );
    }
  }

  if (dashboardEnabled) {
    blockLines.push(`  dashboard: ${fieldsToObjectLiteral("dashboard", {})},`);
  }

  return `// Generated by InfraKit Visual Editor. Values you entered in the property
// panel are used as-is; untouched fields fall back to each package's
// documented defaults. Secrets (cache encryption key, dashboard login,
// load-balancer alert email) are always sourced from environment variables
// here — never written as literals. See README-infrakit.md for exact env
// var names to set in your .env.
module.exports = {
${blockLines.join("\n")}
};
`;
}
